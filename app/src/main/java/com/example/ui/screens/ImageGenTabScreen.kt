@Composable
private fun ProceduralNeonCanvas(
    prompt: String,
    cyan: Color,
    magenta: Color,
    void: Color
) {
    Canvas(
        modifier = Modifier
            .fillMaxWidth()
            .height(220.dp)
            .clip(CyberSmallCutShape)
            .background(void)
    ) {
        val w = size.width
        val h = size.height

        // Background subtle grid
        val gridStep = 24.dp.toPx()
        var gx = 0f
        while (gx < w) {
            drawLine(cyan.copy(alpha = 0.08f), Offset(gx, 0f), Offset(gx, h), 1f)
            gx += gridStep
        }
        var gy = 0f
        while (gy < h) {
            drawLine(cyan.copy(alpha = 0.08f), Offset(0f, gy), Offset(w, gy), 1f)
            gy += gridStep
        }

        // Draw futuristic cyber helix / geometric biology emblem
        val centerX = w / 2f
        val centerY = h / 2f

        // Glowing concentric rings
        drawCircle(
            brush = Brush.radialGradient(
                colors = listOf(cyan.copy(alpha = 0.4f), Color.Transparent),
                center = Offset(centerX, centerY),
                radius = 120.dp.toPx()
            ),
            radius = 120.dp.toPx(),
            center = Offset(centerX, centerY)
        )

        drawCircle(
            color = cyan,
            radius = 70.dp.toPx(),
            center = Offset(centerX, centerY),
            style = Stroke(width = 2.dp.toPx())
        )
        drawCircle(
            color = magenta,
            radius = 45.dp.toPx(),
            center = Offset(centerX, centerY),
            style = Stroke(width = 2.dp.toPx())
        )

        // Draw sine wave / DNA rungs across canvas
        val path1 = Path()
        val path2 = Path()
        val steps = 40
        val amp = 35.dp.toPx()

        for (i in 0..steps) {
            val x = (w * i) / steps
            val angle = (i * 0.35f)
            val y1 = centerY + kotlin.math.sin(angle) * amp
            val y2 = centerY - kotlin.math.sin(angle) * amp

            if (i == 0) {
                path1.moveTo(x, y1.toFloat())
                path2.moveTo(x, y2.toFloat())
            } else {
                path1.lineTo(x, y1.toFloat())
                path2.lineTo(x, y2.toFloat())
            }

            // Draw cross-rung bars
            if (i % 3 == 0) {
                drawLine(
                    color = if (i % 2 == 0) cyan else magenta,
                    start = Offset(x, y1.toFloat()),
                    end = Offset(x, y2.toFloat()),
                    strokeWidth = 1.5.dp.toPx()
                )
                drawCircle(
                    color = Color.White,
                    radius = 3.dp.toPx(),
                    center = Offset(x, y1.toFloat())
                )
                drawCircle(
                    color = Color.White,
                    radius = 3.dp.toPx(),
                    center = Offset(x, y2.toFloat())
                )
            }
        }

        drawPath(path1, cyan, style = Stroke(width = 2.5.dp.toPx()))
        drawPath(path2, magenta, style = Stroke(width = 2.5.dp.toPx()))
    }
}
